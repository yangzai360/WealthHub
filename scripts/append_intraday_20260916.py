# ---- 新闻表按赛道分组（关键新闻用 markdown 超链接） ----
def news_table(track):
    items = [x for x in news if x['track'] == track]
    if not items:
        return '_本档无新增_\n'
    rows = []
    for x in items:
        url = x.get('source_url') or ''
        ttl = x['title']
        # 关键新闻（强度≥60 或方向明确）用超链接；标题过长则截断到 130 字
        if url and (x['strength'] >= 60 or x['direction'] != '中性'):
            shown = ttl if len(ttl) <= 150 else ttl[:150] + '…'
            cell = f'[{shown}]({url})'
        else:
            cell = ttl if len(ttl) <= 150 else ttl[:150] + '…'
        s = f"{x['strength']}/{x['confidence']}"
        if x['strength'] >= 70 or x['direction'] != '中性':
            s = f"**{s}**"
        d = x['direction']
        if d != '中性':
            d = f'**{d}**'
        rows.append(f"| {cell} | {x['sentiment']} | {s} | {d} | {x['volatility']} |")
    return "\n".join(rows) + "\n"

