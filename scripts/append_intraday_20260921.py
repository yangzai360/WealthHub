def news_table(track):
    items = [x for x in news if x['track'] == track]
    if not items:
        return '_本档无新增_\n'
    rows = []
    for x in items:
        url = x.get('source_url') or ''
        ttl = x['title']
        shown = ttl if len(ttl) <= 170 else ttl[:170] + '…'
        cell = f'[{shown}]({url})' if (url and (x['strength'] >= 60 or x['direction'] != '中性')) else shown
        s = f"{x['strength']}/{x['confidence']}"
        if x['strength'] >= 70 or x['direction'] != '中性':
            s = f'**{s}**'
        d = x['direction']
        if d != '中性':
            d = f'**{d}**'
        rows.append(f"| {cell} | {x['sentiment']} | {s} | {d} | {x['volatility']} |")
    return '\n'.join(rows) + '\n'


