def table(track, order=None):
    rows = by_track.get(track, [])
    if order:
        rows = sorted(rows, key=lambda x: -x['strength'])
    out = ['| 事件 | 情绪 | 强度/置信 | 方向 | 波动 |', '|------|------|-----------|------|------|']
    for s in rows:
        st = f"**{s['strength']}/{s['confidence']}**" if s['strength'] >= 75 else f"{s['strength']}/{s['confidence']}"
        out.append(f"| {link(s)} | {s['sentiment']} | {st} | {s['direction']} | {s['volatility']} |")
    return '\n'.join(out)


