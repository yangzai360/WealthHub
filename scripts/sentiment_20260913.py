data = {"model": "deepseek-v4-flash",
        "messages": [{"role": "user", "content": prompt}],
        "max_tokens": 8000, "temperature": 0.3}
req = urllib.request.Request("https://api.deepseek.com/chat/completions",
    data=json.dumps(data).encode(),
    headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"})
for attempt in range(3):
    with urllib.request.urlopen(req, timeout=180) as resp:
        result = json.load(resp)
    content = result['choices'][0]['message'].get('content', '') or ''
    if content.strip():
        break
    print(f'  第{attempt+1}次 content 为空，重试')

s, e = content.find('['), content.rfind(']')
arr = json.loads(content[s:e+1])
out = []
for o in arr:
    i = int(o['idx']) - 1
    out.append({'idx': i+1, 'title': items[i][0][:60], 'track': items[i][1],
                'sentiment': o['sentiment'], 'strength': int(o['strength']),
                'confidence': int(o['confidence']), 'direction': o['direction'],
                'volatility': o['volatility'], 'brief': o.get('brief', '')})

with open(os.path.join(NEWS, 'sentiment-2026-09-13.json'), 'w', encoding='utf-8') as f:
    json.dump({'date': '2026-09-13', 'window': '2026-09-11 18:00 - 2026-09-13 20:00 (周末)', 'items': out},
              f, ensure_ascii=False, indent=1)

for o in out:
    print(f"  {o['idx']:2d} {o['track']:8s} {o['sentiment']} {o['strength']}/{o['confidence']} {o['direction']} {o['volatility']} | {o['brief']}")
