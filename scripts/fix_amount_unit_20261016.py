# 右侧边界（§3.111c 扩展 / §3.112e 比率守卫）：非数字 + 非 %/元/万/亿/点/bp/条/次… 且非 `91 / 183` 形式
# §3.146a：补 `~` 守卫 —— 「A~B 亿元」的**下界**其后跟 `~`，若只靠 `亿元` 守卫则下界会被误补成 `A 元~B 亿元`。
NOT_SUFFIX = (r'(?![\d,.])(?!\s*(?:%|元|万|亿|美元|港元|点|bp|倍|条|次|只|家|个|日|年|月|季|pct|股))'
              r'(?!\s*[~～—－])'
              r'(?!\s*/\s*(?:\d|total|n\b))')

# 上下文守卫（§3.109 复发保护 / §3.112e 语义上下文校验；§3.112e 补充：`hit A / total B` 计数与 n 不得补元）
CTX_GUARD = re.compile(
    r'(n\s*=\s*\d*\s*/\s*\d*\s*/\s*|样本量[^，。；]{0,12}|bytes[^，。；]{0,3}'
    r'|\d{2,}\s*/\s*|指数[^，。；]{0,6}|点位[^，。；]{0,4}|收盘[^，。；]{0,6}|报\s*$|收\s*$'
    r'|(?:负面|正面|中性|利多|利空)\s*$|置信度\s*$|强度\s*$|波动(?:高|中|低)?\s*$'
    r'|净值[^，。；]{0,4}|批价[^，。；]{0,4}|零售[^，。；]{0,4}|终端价[^，。；]{0,4}'
    r'|B\s*/?\s*|条[^，。；]{0,2}|行[^，。；]{0,2}|张[^，。；]{0,2}|亿元[^，。；]{0,2}'
    r'|%（\s*$)'
    r'|(?:adjustedCount|investedUnit|planUnit(?:_sum|_cat_sum)?|unit|份数|份|个品种)[\s=]{0,3}[^，。；]{0,10}'
    # §3.156b（本档新登记）：**「脚本常量对照式」上下文**必须一并跳过 ——
    #   §3.148b 技术项会以 `常量A → 常量B` / `A + B = C（自证）` / `计算项` / `notional` 形式引用脚本字面量，
    #   此类数字**不是报告侧绝对金额**，却是白名单内的同一数值 → 不设守卫必然被误补「元」
    #   （本档实测 10 处全为误伤：371,790.99→370,260.42 各 2 次、59,888.95 2 次、9,191.59 2 次、1,882.46/1,904.44 各 1 次）。
    r'|计算项[^，。；]{0,10}|ARCHIVED|notional[^，。；]{0,14}|自证|LOF[\s）]'
)


def _url_spans(text):
    """markdown 超链接目标与裸 URL 的字符区间（§3.105：URL 不受脱敏/补齐影响）。"""
    spans = []
    for m in re.finditer(r'\]\(([^)\s]+)\)', text):
        spans.append((m.start(1), m.end(1)))
    for m in re.finditer(r'https?://[^\s)\]，。；]+', text):
        spans.append((m.start(), m.end()))
    return spans


def fix(text: str):
    changes = []
    urls = _url_spans(text)
    for amt in AMOUNTS:
        pat = re.compile(r'(?<![\d,.=])([+-]?)' + re.escape(amt) + NOT_SUFFIX)

        def rep(m):
            if any(a <= m.start() and m.end() <= b for a, b in urls):
                return m.group(0)          # URL 内 → 误伤，跳过
            head = text[max(0, m.start() - 30):m.start()]
            if CTX_GUARD.search(head):
                return m.group(0)
            changes.append(m.group(0))
            return m.group(0) + ' 元'

        text = pat.sub(rep, text)
    return text, changes


def main():
    dry = '--dry' in sys.argv
    grand = 0
    for f in TARGETS:
        if not os.path.exists(f):
            print(f'{os.path.relpath(f, REPO)}: 不存在，跳过')
            continue
        s = open(f, encoding='utf-8').read()
        out, ch = fix(s)
        print(f'{os.path.relpath(f, REPO)}: 补「元」{len(ch)} 处')
        if ch:
            print('   ', ch)
        print(f'   白名单 {len(AMOUNTS)} 条；「## 」章节数 {len(re.findall(r"^## ", s, re.M))}；'
              f'「### 」小节数 {len(re.findall(r"^### ", s, re.M))}；正文 {len(s)} 字符')
        grand += len(ch)
        if not dry and ch:
            open(f, 'w', encoding='utf-8').write(out)
    print(f'合计 {grand} 处' + ('（dry-run，未写盘）' if dry else ''))


if __name__ == '__main__':
    main()
