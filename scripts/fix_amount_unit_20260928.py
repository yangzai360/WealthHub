# 右侧边界：必须紧跟非数字字符（排除 2030年 / URL尾号 / n=269 等误伤），
# 且其后不得已是 %/元/万/亿 口径；左侧边界排除紧跟数字或 '='。
NOT_SUFFIX = r'(?![\d,.])(?!\s*(?:%|元|万|亿|美元|港元))'


def fix(text: str):
    changes = []
    # 上下文守卫（§3.109 复发保护）：样本量/字节数/年份等场景下的同形数字不得补「元」
    CTX_GUARD = re.compile(r'(n\s*=\s*\d*\s*/\s*\d*\s*/\s*|样本量[^，。；]{0,12}|bytes[^，。；]{0,3}|\d{2,}\s*/\s*)\s*$')
    for amt in AMOUNTS:
        pat = re.compile(r'(?<![\d,.=])([+-]?)' + re.escape(amt) + NOT_SUFFIX)
        def rep(m):
            head = text[max(0, m.start() - 30):m.start()]
            if CTX_GUARD.search(head):
                return m.group(0)          # 守卫命中：不是金额，不补
            changes.append(m.group(0))
            return m.group(0) + ' 元'
        text = pat.sub(rep, text)
    return text, changes


def main():
    dry = '--dry' in sys.argv
    grand = 0
    for f in TARGETS:
        if not os.path.exists(f):
            print(f'{os.path.relpath(f, REPO)}: 不存在，跳过')
            continue
        s = open(f, encoding='utf-8').read()
        out, ch = fix(s)
        print(f'{os.path.relpath(f, REPO)}: 补「元」{len(ch)} 处')
        if ch:
            print('   ', ch)
        grand += len(ch)
        if not dry and ch:
            open(f, 'w', encoding='utf-8').write(out)
    print(f'合计 {grand} 处' + ('（dry-run，未写盘）' if dry else ''))


if __name__ == '__main__':
    main()
